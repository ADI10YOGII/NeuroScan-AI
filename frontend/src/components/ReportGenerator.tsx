import React from 'react';
import jsPDF from 'jspdf';
import { Download } from 'lucide-react';
import { PredictionResult } from '../utils/api';

interface ReportGeneratorProps {
    result: PredictionResult;
    patientName?: string;
}

export const ReportGenerator: React.FC<ReportGeneratorProps> = ({ result, patientName = "Anonymous" }) => {
    const generatePDF = () => {
        const doc = new jsPDF();
        const date = new Date().toLocaleDateString();

        // Header
        doc.setFillColor(15, 23, 42); // Slate 900
        doc.rect(0, 0, 210, 40, 'F');
        doc.setTextColor(255, 255, 255);
        doc.setFontSize(22);
        doc.text("NeuroScan AI Analysis Report", 20, 25);

        // Patient Info
        doc.setTextColor(51, 65, 85); // Slate 700
        doc.setFontSize(12);
        doc.text(`Date: ${date}`, 20, 55);
        doc.text(`Patient ID: ${patientName}`, 20, 62);
        doc.text(`Scan File: ${result.filename}`, 20, 69);

        // Result Section
        doc.setDrawColor(226, 232, 240);
        doc.line(20, 80, 190, 80);

        doc.setFontSize(16);
        doc.setTextColor(15, 23, 42);
        doc.text("Diagnostic Result", 20, 95);

        const resultColor = result.has_tumor ? [220, 38, 38] : [22, 163, 74];
        doc.setTextColor(resultColor[0], resultColor[1], resultColor[2]);
        doc.setFontSize(24);
        doc.text(result.result.toUpperCase(), 20, 110);

        doc.setTextColor(51, 65, 85);
        doc.setFontSize(14);
        doc.text(`Confidence Score: ${(result.confidence * 100).toFixed(2)}%`, 20, 125);

        // Analysis Details
        doc.setFontSize(12);
        doc.text("AI Analysis Summary:", 20, 145);
        doc.setFontSize(10);
        const splitText = doc.splitTextToSize(result.message + " The model analyzed the MRI scan using a deep convolutional neural network trained on thousands of verified medical images. The analysis focused on identifying abnormal tissue growth patterns characteristic of brain tumors.", 170);
        doc.text(splitText, 20, 155);

        // Footer
        doc.setFontSize(8);
        doc.setTextColor(148, 163, 184);
        doc.text("Disclaimer: This report is generated by an AI system and should be reviewed by a qualified medical professional.", 20, 280);

        doc.save(`NeuroScan_Report_${date.replace(/\//g, '-')}.pdf`);
    };

    return (
        <button
            onClick={generatePDF}
            className="w-full bg-slate-800 hover:bg-slate-700 text-white py-3 px-4 rounded-xl flex items-center justify-center gap-2 transition-all duration-200 border border-slate-700 hover:border-slate-600 shadow-lg shadow-slate-900/20"
        >
            <Download className="h-5 w-5" />
            <span>Download Detailed Medical Report</span>
        </button>
    );
};
